// Builds index.html from src.html as one self-contained file:
// compiled Tailwind CSS, embedded fonts and inline Lucide icons, so the page
// renders fully even where CDNs are blocked. Photos still load from Unsplash.
// Usage: npm install && npm run build
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const { icons } = require('lucide');

const dir = __dirname;
let html = fs.readFileSync(path.join(dir, 'src.html'), 'utf8');

// 1. Tailwind
const css = execFileSync(path.join(dir, 'node_modules/.bin/tailwindcss'),
  ['-c', 'tailwind.config.js', '-i', 'tailwind.input.css', '--minify'], { cwd: dir, stdio: ['ignore', 'pipe', 'ignore'] }).toString();

// 2. Fonts (latin subset, woff2, base64)
const faces = [
  ['cormorant-garamond', 'Cormorant Garamond', [[400, 'normal'], [500, 'normal'], [600, 'normal'], [400, 'italic'], [500, 'italic']]],
  ['plus-jakarta-sans', 'Plus Jakarta Sans', [[400, 'normal'], [500, 'normal'], [600, 'normal'], [700, 'normal']]]
];
const fontCss = faces.flatMap(([pkg, family, variants]) => variants.map(([w, style]) => {
  const file = path.join(dir, `node_modules/@fontsource/${pkg}/files/${pkg}-latin-${w}-${style}.woff2`);
  const b64 = fs.readFileSync(file).toString('base64');
  return `@font-face{font-family:"${family}";font-style:${style};font-weight:${w};font-display:swap;src:url(data:font/woff2;base64,${b64}) format("woff2")}`;
})).join('\n');

// 3. Icons: every kebab-case name used in the page, rendered by a tiny createIcons shim
const names = new Set([...html.matchAll(/data-lucide="([a-z0-9-]+)"/g)].map(m => m[1]));
[...html.matchAll(/icon: '([a-z0-9-]+)'/g)].forEach(m => names.add(m[1]));
['x', 'menu', 'send', 'check', 'arrow-right', 'camera'].forEach(n => names.add(n));
const pascal = n => n.split('-').map(p => p[0].toUpperCase() + p.slice(1)).join('');
const toSvgInner = nodes => nodes.map(([tag, attrs]) =>
  `<${tag} ${Object.entries(attrs).map(([k, v]) => `${k}="${v}"`).join(' ')}/>`).join('');
const map = {};
for (const n of names) {
  const node = icons[pascal(n)];
  if (!node) throw new Error(`Unknown Lucide icon: ${n}`);
  map[n] = toSvgInner(node[2] || node);
}
const iconJs = `window.lucide={createIcons(){document.querySelectorAll('i[data-lucide]').forEach(function(el){var n=el.getAttribute('data-lucide'),b=window.__ICONS[n];if(!b)return;var s=document.createElementNS('http://www.w3.org/2000/svg','svg');s.setAttribute('viewBox','0 0 24 24');s.setAttribute('fill','none');s.setAttribute('stroke','currentColor');s.setAttribute('stroke-width','2');s.setAttribute('stroke-linecap','round');s.setAttribute('stroke-linejoin','round');s.setAttribute('aria-hidden','true');s.setAttribute('class','lucide lucide-'+n+' '+(el.getAttribute('class')||''));s.innerHTML=b;el.replaceWith(s);});}};`;

html = html
  .replace('<!-- build:fonts -->', `<style>${fontCss}</style>`)
  .replace('<!-- build:tailwind -->', `<style>${css}</style>`)
  .replace('<!-- build:icons -->', `<script>window.__ICONS=${JSON.stringify(map)};${iconJs}</script>`);

html = html.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- Generated by build.js from src.html. Edit src.html, then run: npm run build -->');
fs.writeFileSync(path.join(dir, 'index.html'), html);
console.log(`index.html written: ${(Buffer.byteLength(html) / 1024).toFixed(0)} KB, ${names.size} icons`);
