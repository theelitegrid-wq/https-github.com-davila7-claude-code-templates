"""Generate every shot of a short on Kaggle's free GPU with open models, then download them.

Images: Z-Image-Turbo (Apache 2.0), falling back to SDXL base if it can't load.
Clips (optional, ANIMATE=1 per shot): Wan 2.2 TI2V-5B image-to-video (Apache 2.0).

Needs KAGGLE_USERNAME and KAGGLE_KEY (kaggle.com -> Settings -> API -> Create New Token).
The Kaggle account must be phone-verified to use GPU + internet in notebooks.

usage (from daily.py): fetch_shots(shots, out_dir) -> {index: "shots/NN.png" | "shots/NN.mp4"}
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

SLUG = "whatif-shots"

KERNEL = r'''
# Auto-generated by automation/kaggle_shots.py. Runs on a Kaggle GPU.
import json, os, subprocess, sys
SHOTS = json.loads(__SHOTS__)
OUT = "/kaggle/working/shots"
os.makedirs(OUT, exist_ok=True)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "-U", "diffusers", "transformers",
                "accelerate", "sentencepiece", "ftfy", "imageio", "imageio-ffmpeg"], check=True)
import torch
from PIL import Image

W, H = 768, 1344  # 9:16
NEG = "text, watermark, logo, caption, blurry, deformed hands, extra fingers, distorted face, low quality"
log = open(f"{OUT}/log.txt", "w")

def load_image_pipe():
    try:
        from diffusers import ZImagePipeline
        p = ZImagePipeline.from_pretrained("Tongyi-MAI/Z-Image-Turbo", torch_dtype=torch.bfloat16)
        p.enable_model_cpu_offload()
        return "zimage", p
    except Exception as e:
        print("Z-Image unavailable, using SDXL:", e, file=log, flush=True)
        from diffusers import StableDiffusionXLPipeline
        p = StableDiffusionXLPipeline.from_pretrained(
            "stabilityai/stable-diffusion-xl-base-1.0", torch_dtype=torch.float16, variant="fp16")
        p.to("cuda")
        return "sdxl", p

kind, pipe = load_image_pipe()
seed = SHOTS[0].get("seed", 1234) if SHOTS else 1234
for s in SHOTS:
    g = torch.Generator("cuda").manual_seed(seed + s["i"])
    if kind == "zimage":
        img = pipe(prompt=s["prompt"], height=H, width=W, num_inference_steps=9,
                   guidance_scale=0.0, generator=g).images[0]
    else:
        img = pipe(prompt=s["prompt"], negative_prompt=NEG, height=H, width=W, num_inference_steps=30,
                   guidance_scale=6.0, generator=g).images[0]
    img.save(f"{OUT}/{s['i']:02d}.png")
    print("image", s["i"], kind, file=log, flush=True)
del pipe
torch.cuda.empty_cache()

todo = [s for s in SHOTS if s.get("animate")]
if todo:
    try:
        from diffusers import AutoencoderKLWan, WanImageToVideoPipeline
        from diffusers.utils import export_to_video
        mid = "Wan-AI/Wan2.2-TI2V-5B-Diffusers"
        vae = AutoencoderKLWan.from_pretrained(mid, subfolder="vae", torch_dtype=torch.float32)
        wan = WanImageToVideoPipeline.from_pretrained(mid, vae=vae, torch_dtype=torch.bfloat16)
        wan.enable_model_cpu_offload()
        for s in todo:
            img = Image.open(f"{OUT}/{s['i']:02d}.png").convert("RGB").resize((480, 832))
            frames = wan(image=img, prompt=s.get("motion_prompt") or s["prompt"], negative_prompt=NEG,
                         height=832, width=480, num_frames=73, num_inference_steps=30,
                         guidance_scale=5.0).frames[0]
            export_to_video(frames, f"{OUT}/{s['i']:02d}.mp4", fps=24)
            print("clip", s["i"], file=log, flush=True)
    except Exception as e:  # stills still work without clips
        print("Wan failed, stills only:", repr(e), file=log, flush=True)
print("done", file=log, flush=True)
'''


def _kaggle(*args, check=True):
    # The CLI may live in this interpreter's venv rather than on PATH.
    local = Path(sys.executable).parent / "kaggle"
    exe = str(local) if local.exists() else (shutil.which("kaggle") or "kaggle")
    return subprocess.run([exe, *args], capture_output=True, text=True, check=check)


def fetch_shots(shots, out_dir, timeout_min=110):
    user = os.environ.get("KAGGLE_USERNAME")
    if not user or not os.environ.get("KAGGLE_KEY"):
        raise RuntimeError("KAGGLE_USERNAME / KAGGLE_KEY not set")
    ref = f"{user}/{SLUG}"
    with tempfile.TemporaryDirectory() as tmp:
        kdir = Path(tmp)
        (kdir / "kernel.py").write_text(KERNEL.replace("__SHOTS__", repr(json.dumps(shots))))
        (kdir / "kernel-metadata.json").write_text(json.dumps({
            "id": ref, "title": SLUG, "code_file": "kernel.py", "language": "python",
            "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": True,
            "dataset_sources": [], "competition_sources": [], "kernel_sources": [],
        }))
        print(_kaggle("kernels", "push", "-p", str(kdir)).stdout.strip(), flush=True)
    deadline = time.time() + timeout_min * 60
    status = ""
    while time.time() < deadline:
        time.sleep(60)
        status = _kaggle("kernels", "status", ref, check=False).stdout.lower()
        print("[kaggle]", status.strip(), flush=True)
        if "complete" in status or "error" in status or "cancel" in status:
            break
    out_dir = Path(out_dir)
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)
    with tempfile.TemporaryDirectory() as tmp:
        _kaggle("kernels", "output", ref, "-p", tmp, check=False)
        got = {}
        for f in Path(tmp).rglob("*"):
            if f.suffix in (".png", ".mp4"):
                shutil.copy(f, out_dir / f.name)
            if f.name == "log.txt":
                print(f.read_text()[-2000:], flush=True)
    for s in shots:
        clip, still = out_dir / f"{s['i']:02d}.mp4", out_dir / f"{s['i']:02d}.png"
        if clip.exists():
            got[s["i"]] = f"shots/{clip.name}"
        elif still.exists():
            got[s["i"]] = f"shots/{still.name}"
    if "complete" not in status or len(got) < len(shots):
        raise RuntimeError(f"Kaggle job {status.strip() or 'timed out'}; got {len(got)}/{len(shots)} shots")
    return got
